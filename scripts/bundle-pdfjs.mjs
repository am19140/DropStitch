/**
 * Copies pdf.js (from the pdfjs-dist dev dependency) into src/lib/pdfjs.generated.ts as two strings,
 * so the pattern viewer and the PDF text reader work without an internet connection.
 *
 * Run after changing the pdfjs-dist version:  npm run pdfjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const build = join(dirname(require.resolve('pdfjs-dist/package.json')), 'legacy', 'build');
const { version } = require('pdfjs-dist/package.json');

const lib = readFileSync(join(build, 'pdf.min.mjs'), 'utf8');
const worker = readFileSync(join(build, 'pdf.worker.min.mjs'), 'utf8');

const out = `/* eslint-disable */
// Generated by scripts/bundle-pdfjs.mjs from pdfjs-dist ${version} (legacy build). Do not edit.
// pdf.js is Apache-2.0 licensed: https://github.com/mozilla/pdf.js/blob/master/LICENSE

export const PDFJS_VERSION = ${JSON.stringify(version)};
export const PDFJS_LIB: string = ${JSON.stringify(lib)};
export const PDFJS_WORKER: string = ${JSON.stringify(worker)};
`;

writeFileSync(join(root, 'src', 'lib', 'pdfjs.generated.ts'), out);
console.log(`pdf.js ${version}: ${Math.round(out.length / 1024)} KB written to src/lib/pdfjs.generated.ts`);
